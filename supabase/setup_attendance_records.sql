-- Run this only if verify_schema.sql reports public.attendance_records as missing.
-- This is safe to re-run. Access is configured separately by
-- setup_access_policies.sql; this script does not grant user access.

CREATE TABLE IF NOT EXISTS public.attendance_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id text NOT NULL,
  parolee_id text,
  officer_id text,
  status text NOT NULL DEFAULT 'pending',
  check_in_time timestamptz NOT NULL DEFAULT now(),
  location text,
  verified boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid NOT NULL DEFAULT auth.uid()
);

CREATE INDEX IF NOT EXISTS attendance_records_parolee_check_in_idx
  ON public.attendance_records (parolee_id, check_in_time DESC);

ALTER TABLE public.attendance_records ENABLE ROW LEVEL SECURITY;

ALTER TABLE public.attendance_records
  ALTER COLUMN check_in_time SET DEFAULT now(),
  ALTER COLUMN verified SET DEFAULT false,
  ALTER COLUMN created_at SET DEFAULT now(),
  ALTER COLUMN created_by SET DEFAULT auth.uid();

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime'
  ) AND NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'attendance_records'
  ) THEN
    EXECUTE 'ALTER PUBLICATION supabase_realtime ADD TABLE public.attendance_records';
  END IF;
END
$$;

NOTIFY pgrst, 'reload schema';
